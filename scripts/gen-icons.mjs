// Generates src/lib/icons.ts from simple-icons (CC0) so only the paths we use ship to the browser.
// Usage: node scripts/gen-icons.mjs
import { writeFileSync } from "node:fs";
import * as si from "simple-icons";

const SLUGS = {
  cypress: "siCypress", selenium: "siSelenium", appium: "siAppium", copilot: "siGithubcopilot",
  mcp: "siModelcontextprotocol", javascript: "siJavascript", typescript: "siTypescript", java: "siOpenjdk",
  python: "siPython", postman: "siPostman", graphql: "siGraphql", bruno: "siBruno", cucumber: "siCucumber", jmeter: "siApachejmeter", newrelic: "siNewrelic",
  grafana: "siGrafana", jenkins: "siJenkins", githubactions: "siGithubactions", git: "siGit", docker: "siDocker",
  maven: "siApachemaven", gitlab: "siGitlab", splunk: "siSplunk",
  kibana: "siKibana", anthropic: "siAnthropic",
};

const lines = Object.entries(SLUGS).map(([key, name]) => {
  const icon = si[name];
  if (!icon) throw new Error(`simple-icons is missing ${name}`);
  return `  ${key}: { title: ${JSON.stringify(icon.title)}, hex: "#${icon.hex}", path: ${JSON.stringify(icon.path)} },`;
});

writeFileSync(
  new URL("../src/lib/icons.ts", import.meta.url),
  `// Generated by scripts/gen-icons.mjs from simple-icons (CC0). Do not edit by hand.\n` +
    `export type BrandIcon = { title: string; hex: string; path: string };\n\n` +
    `export const ICONS = {\n${lines.join("\n")}\n} satisfies Record<string, BrandIcon>;\n\n` +
    `export type IconKey = keyof typeof ICONS;\n`,
);
console.log(`wrote ${lines.length} icons`);
